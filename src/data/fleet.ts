export const FLEET_MAP: Record<string, AircraftTypeSpec> = Object.fromEntries(
  FLEET_TYPES.map((f) => [f.id, f])
)

/** Resolve an ADS-B ICAO aircraft type designator (e.g. "A20N", "B748") + airline to our Fleet Explorer entry */
export function resolveAircraftType(
  icaoType: string | null | undefined,
  airlineId?: AirlineId
): AircraftTypeSpec | null {
  if (!icaoType) return null
  const code = icaoType.trim().toUpperCase()
  if (code === 'A321' && airlineId === 'GEC') {
    return FLEET_MAP['A321F'] ?? null
  }
  if (FLEET_MAP[code]) return FLEET_MAP[code]
  // Match by icaoCodes array
  const found = FLEET_TYPES.find((f) => f.icaoCodes.includes(code))
  if (found) return found
  // Normalize common variants (e.g. A319 -> A319, A320 -> A320, B789 -> B789, E195/E190)
  if (code.startsWith('A35')) return code.includes('K') || code.includes('10') ? FLEET_MAP['A35K'] : FLEET_MAP['A359']
  if (code.startsWith('B74')) return code.includes('8') ? FLEET_MAP['B748'] : FLEET_MAP['B744']
  if (code.startsWith('A33')) return code.includes('9') ? FLEET_MAP['A339'] : code.includes('2') ? FLEET_MAP['A332'] : FLEET_MAP['A333']
  if (code.startsWith('A34')) return FLEET_MAP['A343']
  if (code.startsWith('A38')) return FLEET_MAP['A388']
  if (code.startsWith('B78')) return FLEET_MAP['B789']
  if (code.startsWith('B77')) {
    if (airlineId === 'GEC') return FLEET_MAP['B77L']
    if (airlineId === 'AUA') return FLEET_MAP['B772']
    return FLEET_MAP['B77W']
  }
  if (code.startsWith('B76')) return FLEET_MAP['B763']
  if (code.startsWith('CRJ')) return FLEET_MAP['CRJ9']
  return null
}

/** Pick best airline-matched photo for an aircraft type if available in gallery */
export function getBestPhotoForAircraft(spec: AircraftTypeSpec, airlineId?: AirlineId) {
  if (airlineId) {
    if (spec.photo.airlineId === airlineId) return spec.photo
    const match = spec.gallery?.find((g) => g.airlineId === airlineId)
    if (match) return match
  }
  return spec.photo
}
